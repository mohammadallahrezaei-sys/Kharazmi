-- اجرا: Supabase > SQL Editor > Run (قابل اجرای مجدد؛ فقط انتهای شرح حادثه «[روز از دست رفته: N]» را می‌گذارد/به‌روز می‌کند)
-- تطبیق: کد پرسنلی (employees.emp_id) + تاریخ حادثه (با تحمل ±۱ روز). نتیجهٔ نهایی نشان می‌دهد کدام ردیف‌ها حادثه‌ای در بهداری پیدا نکردند.
