  ('562','2026-08-10'::date,5,'علی  حاتمی مسجدپیشی','1405/05/19')
),
upd as (
  update public.clinic_incidents ci
  set description = case
        when coalesce(ci.description,'') ~ 'روز از دست رفته:\s*[0-9۰-۹]+'
          then regexp_replace(ci.description, 'روز از دست رفته:\s*[0-9۰-۹]+', 'روز از دست رفته: ' || s.lost, 'g')
        else trim(coalesce(ci.description,'')) || E'\n[روز از دست رفته: ' || s.lost || ']' end
  from src s
  join public.employees e on e.emp_id::text = s.code
  where ci.employee_id = e.id
    and s.lost > 0
    and abs((ci.incident_date::date) - s.d) <= 1
  returning s.code, s.d
)
select s.jdate as "تاریخ شمسی", s.code as "کد پرسنلی", s.nm as "نام", s.lost as "روز استعلاجی",
       case when u.code is not null then 'ثبت شد'
            when s.lost = 0 then 'بدون استعلاجی'
            else 'حادثه‌ای در بهداری پیدا نشد' end as "وضعیت"
from src s left join (select distinct code, d from upd) u on u.code = s.code and u.d = s.d
order by s.d, s.code;
