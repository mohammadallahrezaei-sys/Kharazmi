create table if not exists public.hse_procedures(
  id uuid primary key default gen_random_uuid(),
  title text not null,
  kind text not null default 'سیستمی',
  priority int not null default 2 check (priority between 1 and 3),
  status text not null default 'planned' check (status in ('planned','drafting','review','approved')),
  target_date date,
  owner text,
  doc_no text,
  note text,
  approved_at date,
  active boolean not null default true,
  created_by text,
  created_at timestamptz not null default now()
);
alter table public.hse_procedures enable row level security;
drop policy if exists hse_procedures_all on public.hse_procedures;
create policy hse_procedures_all on public.hse_procedures for all to authenticated using (true) with check (true);
